@web_app.post("/api/v1/search")
async def v1_search(request: Request):
    data = await request.json()
    query = data.get("query", "").strip()
    if not query:
        raise HTTPException(status_code=400, detail="query is required")

    # FTS5 cache check
    fts = FTSCache()
    cached = fts.lookup(query)
    if cached:
        results = [_enrich({"title": t, "url": u}) for t, u in cached]
        asyncio.create_task(_get_preloader().preload(cached[:3]))
        return {"status": "ok", "query": query, "results": results, "cached": True}

    pm = ProviderManager()
    scraper = AsyncContentScraper(provider_manager=pm)
    try:
        bases = pm.get_ranked_search_bases()
        scraper_results, plugin_results = await asyncio.gather(
            scraper.search(query, bases),
            pm.search_plugins(query),
            return_exceptions=True,
        )
        if isinstance(scraper_results, Exception):
            scraper_results = []
        if isinstance(plugin_results, Exception):
            plugin_results = []

        # Merge, dedup by URL (scraper results take priority)
        seen: set = {u for _, u in scraper_results}
        raw = list(scraper_results)
        for title, url in plugin_results:
            if url not in seen:
                seen.add(url)
                raw.append((title, url))

        # Relevance sorting
        def _score(item: Tuple[str, str]) -> float:
            title = item[0].lower()
            q = query.lower()
            if title == q: return 10.0
            
            q_words = [w for w in q.split() if len(w) > 2]
            if not q_words: return 0.0
            
            title_words = title.split()
            
            # Count word matches
            matches = 0
            for qw in q_words:
                if qw in title:
                    matches += 1
                    # Bonus for exact word match
                    if any(tw == qw for tw in title_words):
                        matches += 0.5
            
            # Bonus for phrase match
            if q in title: matches += 2.0
            
            score = float(matches) / len(q_words)
            
            # Penalty for very long titles (often noise)
            if len(title) > 60: score *= 0.8
            
            # Penalty for "random" look (too many non-alphanumeric)
            non_alnum = len([c for c in title if not c.isalnum() and not c.isspace()])
            if non_alnum > 5: score *= 0.7
            
            return score

        raw.sort(key=_score, reverse=True)

        # Filter out generic/low-relevance results
        # Only keep results that match at least one significant query word
        raw = [r for r in raw if _score(r) > 0.5]

        if raw:
            fts.store(query, raw)
        asyncio.create_task(_get_preloader().preload(raw[:3]))
        results = [_enrich({"title": t, "url": u}) for t, u in raw]
        return {"status": "ok", "query": query, "results": results, "cached": False}
    finally:
        await scraper.close()


@web_app.post("/api/search")
async def search(request: Request):
    """Search for movies/shows"""
    try:
        data = await request.json()
        query = data.get("query", "").strip()

        if not query:
            raise HTTPException(status_code=400, detail="Query is required")

        # TMDB-first: real, sanctioned metadata API, not fighting anti-bot.
        # The 9 scraped providers below are ~100% dead (Cloudflare/JWT/JS
        # gates) as of the 2026-07-25 live audit -- kept only as fallback.
        if tmdb_configured():
            tmdb_results = await tmdb_search(query)
            if tmdb_results:
                return {
                    "status": "ok",
                    "query": query,
                    "results": [{"title": r["title"], "url": r["url"]} for r in tmdb_results],
                    "cached": False,
                    "source": "tmdb",
                }

        # FTS5 cache check
        fts = FTSCache()
        cached = fts.lookup(query)
        if cached:
            return {
                "status": "ok",
                "query": query,
                "results": [{"title": t, "url": u} for t, u in cached],
                "cached": True,
            }

        pm = ProviderManager()
        scraper = AsyncContentScraper(provider_manager=pm)
        try:
            bases = pm.get_ranked_search_bases()
            raw = await scraper.search(query, bases)
            if raw:
                fts.store(query, raw)
            return {
                "status": "ok",
                "query": query,
                "results": [{"title": title, "url": url} for title, url in raw],
                "cached": False,
            }
        finally:
            await scraper.close()
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


