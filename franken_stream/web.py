# ── WebSocket ─────────────────────────────────────────────────────────────────

async def _broadcast(msg: dict) -> None:
    """Push a JSON message to all connected WebSocket clients."""
    dead: Set[WebSocket] = set()
    for ws in list(_ws_clients):
        try:
            await ws.send_json(msg)
        except Exception:
            dead.add(ws)
    _ws_clients.difference_update(dead)


@web_app.websocket("/api/ws")
async def websocket_endpoint(ws: WebSocket):
    await ws.accept()
    _ws_clients.add(ws)
    await ws.send_json({"type": "connected", "message": "Franken-Stream WebSocket ready"})
    try:
        while True:
            data = await ws.receive_json()
            if data.get("action") == "ping":
                await ws.send_json({"type": "pong"})
            elif data.get("action") == "status":
                status = await _player.get_status()
                await ws.send_json({"type": "status", **status})
    except WebSocketDisconnect:
        pass
    finally:
        _ws_clients.discard(ws)


