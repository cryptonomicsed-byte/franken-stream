# ── v1 Player (agent one-shot spin-up) ───────────────────────────────────────

@web_app.post("/api/v1/player/spin-up")
async def player_spin_up(request: Request):
    """
    Agent one-shot: search → extract embed → play.
    POST {"query": "Oppenheimer", "quality": "best"}
    """
    data = await request.json()
    query = data.get("query", "").strip()
    if not query:
        raise HTTPException(status_code=400, detail="query is required")

    # 1. Search
    fts = FTSCache()
    cached = fts.lookup(query)
    if cached:
        raw = cached
    else:
        pm = ProviderManager()
        scraper = AsyncContentScraper(provider_manager=pm)
        try:
            bases = pm.get_ranked_search_bases()
            raw = await scraper.search(query, bases)
            if raw:
                fts.store(query, raw)
        finally:
            await scraper.close()

    if not raw:
        raise HTTPException(status_code=404, detail=f"No results found for: {query}")

    title, page_url = raw[0]

    # 2. Extract embed
    pm2 = ProviderManager()
    scraper2 = AsyncContentScraper(provider_manager=pm2)
    try:
        embed_url = await scraper2.fetch_embed_from_page(page_url)
        play_url = embed_url or page_url
    finally:
        await scraper2.close()

    # 3. Spin up player
    result = await _player.play(play_url, title=title)
    if result.get("status") == "error":
        raise HTTPException(status_code=500, detail=result.get("message", "Player error"))

    media_id = hashlib.md5(play_url.encode()).hexdigest()[:12]
    _watchlist.add(media_id, title, play_url)
    await _broadcast({"type": "playback", "event": "spin-up", "title": title})
    return {
        "status": "playing",
        "media": {"title": title, "url": play_url},
        "message": f"Now playing: {title}",
        **result,
    }


