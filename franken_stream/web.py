# ── v1 Playback (direct URL) ──────────────────────────────────────────────────

@web_app.post("/api/v1/play")
async def v1_play(request: Request):
    data = await request.json()
    url = data.get("url", "").strip()
    title = data.get("title", "")
    if not url:
        raise HTTPException(status_code=400, detail="url is required")
    result = await _player.play(url, title=title)
    if result.get("status") == "playing":
        media_id = hashlib.md5(url.encode()).hexdigest()[:12]
        _watchlist.add(media_id, title or url, url)
    await _broadcast({"type": "playback", "event": "started", **result})
    return result


@web_app.post("/api/v1/control")
async def v1_control(request: Request):
    data = await request.json()
    action = data.get("action", "")
    ok = False

    if action == "pause":
        ok = await _player.pause()
    elif action == "resume":
        ok = await _player.resume()
    elif action == "stop":
        await _player.stop()
        ok = True
    elif action == "seek":
        position = data.get("position")
        if position is None:
            raise HTTPException(status_code=400, detail="position required for seek")
        ok = await _player.seek(int(position))
    else:
        raise HTTPException(status_code=400, detail=f"Unknown action: {action}")

    await _broadcast({"type": "playback", "event": action, "ok": ok})
    return {"action": action, "ok": ok}


